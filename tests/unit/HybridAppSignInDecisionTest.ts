import CONFIG from '@src/CONFIG';
import ONYXKEYS from '@src/ONYXKEYS';

import HybridAppModule from '@expensify/react-native-hybrid-app';
import Onyx from 'react-native-onyx';

import getOnyxValue from '../utils/getOnyxValue';
import waitForBatchedUpdates from '../utils/waitForBatchedUpdates';

jest.mock('@src/CONFIG', () => {
    const actual = jest.requireActual<{default: Record<string, unknown>}>('@src/CONFIG');
    return {
        __esModule: true,
        default: {...actual.default, IS_HYBRID_APP: true},
    };
});

jest.mock('@libs/Navigation/Navigation', () => ({
    clearPreloadedRoutes: jest.fn(),
}));

Onyx.init({keys: ONYXKEYS});

// Importing the module registers the Onyx subscriptions that drive the sign-in decision
// eslint-disable-next-line import/first
import '@libs/HybridApp';

const CLASSIC_USER = {classicRedirect: {dismissed: true, timestamp: new Date(), completedHybridAppOnboarding: true}};
const NEW_DOT_USER = {classicRedirect: {dismissed: false, timestamp: new Date(), completedHybridAppOnboarding: true}};

function signIn(tryNewDot: Record<string, unknown>, account: Record<string, unknown>) {
    return Onyx.multiSet({
        [ONYXKEYS.HYBRID_APP]: {useNewDotSignInPage: true},
        [ONYXKEYS.CREDENTIALS]: {autoGeneratedLogin: 'login', autoGeneratedPassword: 'password'},
        [ONYXKEYS.NVP_TRY_NEW_DOT]: tryNewDot,
        [ONYXKEYS.ACCOUNT]: account,
        [ONYXKEYS.SESSION]: {authToken: 'authToken', accountID: 1, email: 'user@expensify.com'},
    });
}

describe('HybridApp sign-in decision', () => {
    let signInToOldDotSpy: jest.SpiedFunction<typeof HybridAppModule.signInToOldDot>;
    let closeNativeAppSpy: jest.SpiedFunction<typeof HybridAppModule.closeReactNativeApp>;

    beforeEach(async () => {
        jest.clearAllMocks();
        signInToOldDotSpy = jest.spyOn(HybridAppModule, 'signInToOldDot').mockImplementation(() => {});
        closeNativeAppSpy = jest.spyOn(HybridAppModule, 'closeReactNativeApp').mockImplementation(() => {});
        await Onyx.clear();
        await waitForBatchedUpdates();
    });

    afterEach(() => {
        jest.restoreAllMocks();
    });

    it('keeps a Classic user in NewDot for the required 2FA setup and remembers the deferred handoff', async () => {
        // Given a Classic user whose account must set up 2FA before it can be used
        expect(CONFIG.IS_HYBRID_APP).toBe(true);
        await signIn(CLASSIC_USER, {needsTwoFactorAuthSetup: true, requiresTwoFactorAuth: false});
        await waitForBatchedUpdates();

        // Then sign-in holds the user in NewDot instead of closing it
        expect(signInToOldDotSpy).toHaveBeenCalled();
        expect(closeNativeAppSpy).not.toHaveBeenCalled();

        // Then the decision is stored so the 2FA success screen can return the user to OldDot later
        const hybridApp = await getOnyxValue(ONYXKEYS.HYBRID_APP);
        expect(hybridApp?.readyToShowAuthScreens).toBe(true);
        expect(hybridApp?.useNewDotSignInPage).toBe(false);
        expect(hybridApp?.shouldReturnToOldDotAfter2FA).toBe(true);
    });

    it('does not remember a handoff for a NewDot user who must set up 2FA', async () => {
        // Given a NewDot user whose account must set up 2FA
        await signIn(NEW_DOT_USER, {needsTwoFactorAuthSetup: true, requiresTwoFactorAuth: false});
        await waitForBatchedUpdates();

        // Then the user stays in NewDot and no OldDot handoff is pending
        expect(closeNativeAppSpy).not.toHaveBeenCalled();
        const hybridApp = await getOnyxValue(ONYXKEYS.HYBRID_APP);
        expect(hybridApp?.readyToShowAuthScreens).toBe(true);
        expect(hybridApp?.shouldReturnToOldDotAfter2FA).toBe(false);
    });

    it('closes NewDot right away for a Classic user who does not need 2FA setup', async () => {
        // Given a Classic user with nothing blocking the account
        await signIn(CLASSIC_USER, {needsTwoFactorAuthSetup: false, requiresTwoFactorAuth: false});
        await waitForBatchedUpdates();

        // Then sign-in hands off to OldDot immediately and leaves no pending handoff behind
        expect(closeNativeAppSpy).toHaveBeenCalledWith({shouldSetNVP: false});
        const hybridApp = await getOnyxValue(ONYXKEYS.HYBRID_APP);
        expect(hybridApp?.shouldReturnToOldDotAfter2FA).toBe(false);
    });
});
